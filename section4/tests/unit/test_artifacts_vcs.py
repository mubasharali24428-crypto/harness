def test_stale_base_is_computed_audited_once_and_cleared_by_a_rebase(env):
    env.git("lead", "r1", baseBranch="main", baseSha=SHA_A, observedHeadSha=SHA_A)
    assert env.audit("base.stale_detected") == []
    stale = env.git("lead", "r1", observedHeadSha=SHA_B)
    assert stale["base"]["stale"] is True and stale["mergeRequirement"] == (
        "rebase_or_merge_required"
    )
    env.git("lead", "r1", observedHeadSha=SHA_C)  # still stale: not a second detection
    assert len(env.audit("base.stale_detected")) == 1
    d = json.loads(env.audit("base.stale_detected")[0].detail)
    assert d["baseSha"] == SHA_A and d["observedHeadSha"] == SHA_B and d["runId"] == "r1"
    rebased = env.git("lead", "r1", baseSha=SHA_C)
    assert rebased["base"]["stale"] is False and rebased["mergeRequirement"] is None
    env.git("lead", "r1", observedHeadSha=SHA_B)  # stale again is a new detection
    assert len(env.audit("base.stale_detected")) == 2


