    perms = env.as_("lead").get(env.url("r1", "/git-permissions")).json()
    assert "MERGE_REJECTED" in perms["blockers"] and not perms["caller"]["merge"]["allowed"]
    assert env.q("SELECT COUNT(*) AS n FROM merge_approvals")[0].n == 2  # nothing rewritten


