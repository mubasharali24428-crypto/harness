    env.set_diff("r1", git_diff(("a.py", ["v2"])))
    [new] = env.changes("lead", "r1")["items"]
    assert new["id"] != old["id"] and new["reviewState"] == "pending"
    err(
        env.as_("lead").post(
            env.url("r1", f"/changes/{old['id']}/review"),
            json={"decision": "approved", "diffSha": old["diffSha"]},
        ),
        409,
        "CHANGE_SUPERSEDED",
    )
    env.set_diff("r1", git_diff(("a.py", ["v1"])))  # going back revives the reviewed row
    [back] = env.changes("lead", "r1")["items"]
    assert back["id"] == old["id"] and back["reviewState"] == "approved"


