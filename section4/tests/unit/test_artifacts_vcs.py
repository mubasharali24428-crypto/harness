def test_lineage_runs_from_the_task_request_to_the_accepted_result(env):
    env.x(
        "INSERT INTO task_specs (run_id, team_id, statement, version, updated_at) VALUES"
        " ('r1', 'team-a', 'add a feature', 3, :t)",
        t=env.clock["t"],
    )
    env.plan("r1", 1, "superseded")
    env.plan("r1", 2, "approved")
    data = env.ready("r1")
    env.x(
        "INSERT INTO run_completion (run_id, agent_state, human_state)"
        " VALUES ('r1', 'reported', 'accepted')"
    )
    env.merge("lead", "r1", data)
    base = env.put("lead", "r1", "log.txt", b"output log", kind="log")
    child = env.put("lead", "r1", "summary.txt", b"summary", kind="output", derivedFrom=base["id"])
    out = env.as_("view").get(env.url("r1", "/lineage")).json()
    assert out["complete"] is True and out["missing"] == []
    assert all(out["stages"].values())
    kinds = {}
    for n in out["nodes"]:
        kinds.setdefault(n["kind"], []).append(n)
    assert {k: len(v) for k, v in kinds.items()} == {
        "task": 1,
        "plan_version": 2,
        "change": 2,
        "completion": 1,
        "merge_approval": 1,
        "artifact": 2,
    }
    rels = {(e["from"]["kind"], e["to"]["kind"], e["relation"]) for e in out["edges"]}
    assert {
        ("task", "plan_version", "planned_as"),
        ("plan_version", "change", "implemented_by"),
        ("change", "completion", "accepted_in"),
        ("change", "merge_approval", "covered_by"),
        ("completion", "merge_approval", "merge_decided_in"),
        ("task", "artifact", "produced"),
        ("artifact", "artifact", "derived_from"),
    } <= rels
    approved = next(n for n in kinds["plan_version"] if n["state"] == "approved")
    impl = [e for e in out["edges"] if e["relation"] == "implemented_by"]
    assert {e["from"]["id"] for e in impl} == {approved["id"]}
    assert {"id": child["id"]}.items() <= next(
        n for n in kinds["artifact"] if n["id"] == child["id"]
    ).items()
    assert "statement" not in json.dumps(out) and "add a feature" not in json.dumps(out)


