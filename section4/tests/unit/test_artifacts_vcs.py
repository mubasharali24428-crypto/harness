# ------------------------------------------------------------------- diff rendering


def _nasty_diff():
    big = "".join(f"+line {i}\n" for i in range(2100))
    return (
        git_diff(("src/app.py", ["print('<script>alert(1)</script>')", "x = 1\x1b[31m‮"]))
        + "diff --git a/logo.png b/logo.png\nindex 1..2 100644\n"
        "Binary files a/logo.png and b/logo.png differ\n"
        + git_diff(("package-lock.json", ["{}"]), ("dist/app.min.js", ["a" * 1500]))
        + "diff --git a/big.txt b/big.txt\n--- a/big.txt\n+++ b/big.txt\n@@ -0,0 +1,2100 @@\n"
        + big
        + "diff --git a/link b/link\nnew file mode 120000\nindex 0..1\n--- /dev/null\n+++ b/link\n"
        "@@ -0,0 +1 @@\n+target\n"
        + "diff --git a/../../etc/passwd b/../../etc/passwd\n--- a/../../etc/passwd\n"
        "+++ b/../../etc/passwd\n@@ -1 +1 @@\n-a\n+b\n"
        + git_diff(("gen.py", ["# @generated by tool", "x = 1"]))
    )


def test_diff_is_structured_json_with_safe_handling_of_binary_large_generated_files(env):
    env.set_diff("r1", _nasty_diff())
    r = env.as_("view").get(env.url("r1", "/diff"))
    assert r.status_code == 200
    assert r.headers["content-type"].startswith("application/json")
    assert r.headers["x-content-type-options"] == "nosniff"
    body = r.json()
    assert body["render"] == "text-only" and body["format"] == "unified-structured"
    files = {f["path"]: f for f in body["files"]}
    assert files["src/app.py"]["patchOmitted"] is None
    patch = files["src/app.py"]["patch"]
    assert "<script>alert(1)</script>" in patch  # data, not markup: the client uses textContent
    assert "\x1b" not in patch and "‮" not in patch  # control and bidi characters replaced
    for path, why in (
        ("logo.png", "binary"),
        ("package-lock.json", "generated"),
        ("dist/app.min.js", "generated"),
        ("big.txt", "large"),
        ("gen.py", "generated"),
    ):
        f = files[path]
        assert f["patch"] is None and f["patchOmitted"] == why and f["flags"][why], path
        assert f["diffSha"] and f["additions"] + f["deletions"] >= 0
    assert files["dist/app.min.js"]["flags"]["minified"] is True
    assert files["link"]["flags"]["symlink"] is True
    unsafe = [f for f in body["files"] if f["pathRejected"]]
    assert len(unsafe) == 1 and unsafe[0]["path"] == "[unsafe path]"


