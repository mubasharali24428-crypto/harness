-- Run with plenary.nvim: nvim --headless -c "PlenaryBustedDirectory spec"  (NOT run in the build
-- environment: no Neovim/Lua interpreter available there; see session-3 report).
local core = require("harness.core")
describe("core", function()
  it("allows https and loopback http only", function()
    assert.are.equal("https://h.example.com", core.safe_base("https://h.example.com/"))
    assert.are.equal("http://localhost:8001", core.safe_base("http://localhost:8001"))
    assert.is_nil((core.safe_base("http://h.example.com")))
    assert.is_nil((core.safe_base("https://u:p@h.example.com")))
    assert.is_nil((core.safe_base("not a url")))
  end)
  it("redacts bearer values and the literal token", function()
    assert.are.equal("Bearer [REDACTED]", core.redact("Bearer abc.def-1234567", nil))
    assert.are.equal("x [REDACTED] y", core.redact("x tok_secret_1 y", "tok_secret_1"))
  end)
  it("keeps the token out of argv by using a curl config body", function()
    local cfg = core.curl_config("POST", "https://h/x", "tok_secret_1", '{"a":1}')
    assert.is_truthy(cfg:find("authorization: Bearer tok_secret_1", 1, true))
    assert.is_truthy(cfg:find('request = "POST"', 1, true))
  end)
  it("splits curl output into body and status", function()
    local body, status = core.split_response('{"ok":true}\n200')
    assert.are.equal('{"ok":true}', body); assert.are.equal(200, status)
  end)
end)
