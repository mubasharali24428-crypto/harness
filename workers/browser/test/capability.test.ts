import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  assertCapabilityOrigin,
  mintCapability,
  verifyCapability,
  type CapabilityPayload,
} from "../src/capability.js";
import { WorkerError } from "../src/types.js";
import { mintFor, testIdentity, TEST_SECRET } from "./support/harness.js";

describe("capability tokens", () => {
  it("round-trips mint → verify", () => {
    const identity = testIdentity();
    const token = mintFor(identity, ["http://127.0.0.1:4100"], { nowSec: 1000 });
    const payload = verifyCapability(token, {
      secret: TEST_SECRET,
      now: 1001,
      binding: identity,
    });
    expect(payload.op).toBe("browser");
    expect(payload.allowedOrigins).toEqual(["http://127.0.0.1:4100"]);
  });

  it("rejects a tampered payload", () => {
    const identity = testIdentity();
    const token = mintFor(identity, ["http://127.0.0.1:4100"], { nowSec: 1000 });
    const [prefix, body, sig] = token.split(".");
    const decoded = JSON.parse(Buffer.from(body!, "base64url").toString("utf8")) as Record<
      string,
      unknown
    >;
    decoded.runId = "run-other";
    const forged = Buffer.from(JSON.stringify(decoded)).toString("base64url");
    try {
      verifyCapability(`${prefix}.${forged}.${sig}`, {
        secret: TEST_SECRET,
        now: 1001,
        binding: identity,
      });
      expect.unreachable();
    } catch (error) {
      expect((error as WorkerError).code).toBe("CAPABILITY_INVALID");
    }
  });

  it("rejects a wrong secret", () => {
    const identity = testIdentity();
    const token = mintFor(identity, ["http://127.0.0.1:4100"], { nowSec: 1000 });
    try {
      verifyCapability(token, { secret: "other-secret", now: 1001, binding: identity });
      expect.unreachable();
    } catch (error) {
      expect((error as WorkerError).code).toBe("CAPABILITY_INVALID");
    }
  });

  it("rejects expired tokens", () => {
    const identity = testIdentity();
    const token = mintFor(identity, ["http://127.0.0.1:4100"], { nowSec: 1000, ttlSeconds: 10 });
    try {
      verifyCapability(token, { secret: TEST_SECRET, now: 1010, binding: identity });
      expect.unreachable();
    } catch (error) {
      expect((error as WorkerError).code).toBe("CAPABILITY_EXPIRED");
    }
  });

  it("binds to the session identity", () => {
    const token = mintFor(testIdentity({ runId: "run-1" }), ["http://127.0.0.1:4100"], {
      nowSec: 1000,
    });
    try {
      verifyCapability(token, {
        secret: TEST_SECRET,
        now: 1001,
        binding: testIdentity({ runId: "run-2" }),
      });
      expect.unreachable();
    } catch (error) {
      expect((error as WorkerError).code).toBe("CAPABILITY_SCOPE");
    }
  });

  it("scopes navigation to the granted origins", () => {
    const identity = testIdentity();
    const payload = verifyCapability(
      mintFor(identity, ["http://127.0.0.1:4100"], { nowSec: 1000 }),
      { secret: TEST_SECRET, now: 1001, binding: identity },
    );
    expect(() => assertCapabilityOrigin(payload, "http://127.0.0.1:4100")).not.toThrow();
    try {
      assertCapabilityOrigin(payload, "http://127.0.0.1:4101");
      expect.unreachable();
    } catch (error) {
      expect((error as WorkerError).code).toBe("CAPABILITY_SCOPE");
    }
  });

  it("verifies the cross-language golden fixture (generated by Python S5)", () => {
    const fixturePath = join(__dirname, "fixtures", "browser_cap_golden.json");
    const fixture = JSON.parse(readFileSync(fixturePath, "utf8")) as {
      secret: string;
      now: number;
      token: string;
      payload: CapabilityPayload;
    };
    const payload = verifyCapability(fixture.token, {
      secret: fixture.secret,
      now: fixture.now,
      binding: {
        teamId: fixture.payload.teamId,
        projectId: fixture.payload.projectId,
        runId: fixture.payload.runId,
      },
    });
    expect(payload).toEqual(fixture.payload);
    // And our own mint agrees byte-for-byte with the Python-produced token.
    expect(mintCapability(fixture.secret, fixture.payload)).toBe(fixture.token);
  });
});
