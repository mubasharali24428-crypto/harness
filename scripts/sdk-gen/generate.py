def ts_type(model: SpecModel, schema: Any) -> str:
    """JSON-schema fragment -> TypeScript type expression."""
    if not isinstance(schema, dict) or not schema:
        return "unknown"
    if "$ref" in schema:
        target = schema["$ref"].rsplit("/", 1)[-1]
        return model.aliases.get(target, "unknown")
    if "anyOf" in schema:
        branches = [ts_type(model, b) for b in schema["anyOf"]]
        return " | ".join(dict.fromkeys(branches))
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    stype = schema.get("type")
    if stype == "null":  # bare null branch (FastAPI optional bodies)
        return "null"
    if stype == "string":
        return "string"
    if stype == "integer":
        return "number"
    if stype == "number":
        return "number"
    if stype == "boolean":
        return "boolean"
    if stype == "array":
        items = ts_type(model, schema.get("items"))
        # Parenthesize unions so T[] never parses as (T | U)[].  The Python
        # emitter has the same subtlety and ignores it — documentation-grade.
        if "|" in items:
            items = f"({items})"
        return f"{items}[]"
    if stype == "object":
        return "{ [key: string]: unknown }"
    return "unknown"


def ts_optional(schema: dict[str, Any] | None) -> bool:
    """True when the fragment is explicitly nullable on the wire."""
    if isinstance(schema, dict):
        for b in schema.get("anyOf", []):
            if isinstance(b, dict) and b.get("type") == "null":
                return True
        if schema.get("type") == "null":
            return True
    return False


def ts_safe_prop(name: str) -> tuple[str, bool]:
    """Wire key -> safe property name. Returns (emitted_name, needs_quotes)."""
    if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) and not keyword.iskeyword(name):
        return name, False
    return name.replace('"', '\\"'), True


def render_ts_models(model: SpecModel) -> str:
    """Emit interfaces / union type aliases for components.schemas."""
    blocks: list[str] = []
    for schema_name in sorted(model.schemas):
        alias = model.aliases[schema_name]
        s = model.schemas[schema_name]
        props = s.get("properties")
        if isinstance(props, dict):
            required = set(s.get("required", []))
            rows: list[tuple[str, str]] = []
            for pn in props:
                ps = props[pn]
                emitted, quoted = ts_safe_prop(pn)
                key = f'"{emitted}"' if quoted else emitted
                ptype = ts_type(model, ps)
                # `name?: T` already admits undefined; add `| undefined`
                # only when the key stays REQUIRED but the wire allows null.
                if ts_optional(ps) and pn in required:
                    ptype = f"{ptype} | undefined"
                note = "" if pn in required else "  // optional"
                rows.append((f"  {key}{'?' if pn not in required else ''}: {ptype};",
                             note))
            req_doc = (f" Required keys: {', '.join(sorted(required))}."
                       if required else "")
            blocks.append("\n".join([
                f"/** {schema_name}.{req_doc} */",
                f"export interface {alias} {{",
                *(row + note for row, note in rows),
                "}",
            ]))
            continue
        t = ts_type(model, s)
        if t != "unknown":
            blocks.append(f"/** {schema_name} */\nexport type {alias} = {t};")
        else:
            blocks.append(f"/** {schema_name} — spec carried no usable shape "
                          f"(kept opaque). */\nexport type {alias} = unknown;")
    return "\n\n".join(blocks)


def build_ts_method(model: SpecModel, path: str, method: str,
                    op: dict[str, Any], used_names: dict[str, int]) -> str:
    """Emit one typed client method mirroring the Python stub's signature."""
    summary = (op.get("summary") or op.get("operationId") or "").strip()
    raw_parts = re.findall(r"\{([^}]+)\}", path)

    path_param_map: dict[str, str] = {}
    query_items: list[tuple[str, str]] = []
    for p in op.get("parameters", []):
        pname_raw = p.get("name", "")
        pname = snake_case(pname_raw)
        if p.get("in") == "path":
            path_param_map[pname_raw] = pname
        elif p.get("in") == "query":
            query_items.append((pname_raw, pname))

    body_schema = ((op.get("requestBody", {}) or {}).get("content", {})
                   or {}).get("application/json", {}).get("schema")
    body_optional = False
    body_type: str | None = None
    if body_schema is not None:
        body_type = model.resolve(body_schema)
        if body_type.endswith(" | None") or body_type == "None":
            body_optional = True
            body_type = body_type.replace(" | None", "") or "typing.Any"
        elif body_schema.get("type") == "object" and "$ref" not in body_schema \
                and "anyOf" not in body_schema:
            body_optional = True
    has_body = body_type is not None
    ts_body_type = None if body_type is None else _py_to_ts_type(body_type)

    # -- signature ------------------------------------------------------------
    params: list[str] = []
    seen: set[str] = set()

    def add_param(name: str, ptype: str, required: bool) -> None:
        nm, i = name, 2
        while nm in seen:
            nm = f"{name}{i}"
            i += 1
        seen.add(nm)
        params.append(f"{nm}: {ptype}" if required
                      else f"{nm}?: {ptype}")

    for pname_raw in raw_parts:
        pname = path_param_map.get(pname_raw, snake_case(pname_raw))
        add_param(pname, "string", True)
    if has_body:
        bt = ts_body_type or "unknown"
        if bt.startswith("{"):
            bt = f"({bt})"   # inline object literal types need parens
        add_param("body", bt, not body_optional)
    param_schemas = {p.get("name"): (p.get("schema") or {})
                     for p in op.get("parameters", [])}
    for qraw, qlocal in query_items:
        add_param(qlocal, _py_to_ts_type(model.resolve(param_schemas.get(qraw))),
                  False)

    ret = _py_to_ts_type(model.response_type(op))

    # -- method name (same derivation as the Python stub) ----------------------
    op_id = op.get("operationId") or ""
    candidate = snake_case(op_id.split("_api_v1_")[0]) if op_id else ""
    if not candidate or len(candidate) > 60:
        frag = "".join(w.title() for w in re.findall(r"[A-Za-z0-9]+", path))
        candidate = snake_case(f"{method}_{frag}")
    if path == "/health":
        candidate = "health"  # FastAPI opIds here are noisy (health_health_get)
    count = used_names.get(candidate, 0)
    used_names[candidate] = count + 1
    mname = candidate if count == 0 else f"{candidate}_{count + 1}"

    # -- body ------------------------------------------------------------------
    fmt_path = path
    for pname_raw in raw_parts:
        fmt_path = fmt_path.replace(
            "{" + pname_raw + "}",
            "${encodeURIComponent(" + path_param_map.get(pname_raw, snake_case(pname_raw)) + ")}",
        )

    lines: list[str] = []
    sig_params = ", ".join(params)
    lines.append(f"  /** {summary}")
    lines.append(f"   *  {method.upper()} {path} */")
    lines.append(f"  {mname}({sig_params}): Promise<{ret}> {{")
    # `_path` mirrors the Python stubs' local name; a bare `path` would collide
    # with operations that take a `path` parameter.
    lines.append("    const _path = `" + fmt_path + "`;")
    # HarnessHttp.request signature: (baseUrl, path, method, body?, params?).
    # Always pass the 4th slot so params never shift into the body position.
    call_args = ['this.baseUrl', '_path', f'"{method.upper()}"',
                 "body" if has_body else "undefined"]
    if query_items:
        qpairs = ", ".join(
            f'{json.dumps(qraw)}: {qlocal}' for qraw, qlocal in query_items)
        lines.append(f"    const params: Record<string, unknown> = {{{qpairs}}};")
        call_args.append("params")
    lines.append(f"    return this.http.request<{ret}>({', '.join(call_args)});")
    lines.append("  }")
    return "\n".join(lines)


def _split_top(expr: str, sep: str) -> list[str]:
    """Split on ``sep`` at bracket/quote depth zero."""
    parts: list[str] = []
    depth, quote, start = 0, "", 0
    for i, ch in enumerate(expr):
        if quote:
            if ch == quote:
                quote = ""
        elif ch in "'\"":
            quote = ch
        elif ch in "[({":
            depth += 1
        elif ch in "])}":
            depth -= 1
        elif ch == sep and depth == 0:
            parts.append(expr[start:i])
            start = i + 1
    parts.append(expr[start:])
    return parts


def _py_to_ts_type(py_type: str) -> str:
    """Translate the shared resolver's Python type expression to TypeScript.

    The grammar is exactly what ``SpecModel.resolve`` emits: unions with
    ``None``, scalars, schema aliases, ``list[T]``, ``dict[str, T]`` and
    ``typing.Literal[...]``. Recursive descent so nested containers come out
    right (``list[list[str]]`` -> ``string[][]``); chained .replace() would
    miss scalars buried inside containers.
    """

    def convert(s: str) -> str:
        s = s.strip()
        pieces = _split_top(s, "|")
        if len(pieces) > 1:
            return " | ".join(convert(p) for p in pieces)
        if s == "None":
            return "null"
        if s == "typing.Any":
            return "unknown"
        if s == "str":
            return "string"
        if s in ("int", "float"):
            return "number"
        if s == "bool":
            return "boolean"
        m = re.fullmatch(r"list\[(.+)\]", s)
        if m:
            inner = convert(m.group(1))
            # Parenthesize unions so T | U[] never reads as (T | U)[].
            return f"({inner})[]" if "|" in inner else f"{inner}[]"
        m = re.fullmatch(r"dict\[str,\s*(.+)\]", s)
        if m:
            return f"Record<string, {convert(m.group(1))}>"
        m = re.fullmatch(r"typing\.Literal\[(.+)\]", s, re.DOTALL)
        if m:
            # SpecModel emits Python repr values separated by commas. Convert
            # each value separately so a multi-value Literal stays a TS union.
            values = _split_top(m.group(1), ",")
            return " | ".join(json.dumps(ast.literal_eval(value.strip()))
                               for value in values if value.strip())
        return s.replace("typing.", "")  # schema alias / class name

    out = convert(py_type)
    return re.sub(r"\s+", " ", out).strip()


def generate_ts_service_module(name: str, model: SpecModel) -> str:
    port = DEFAULT_PORTS.get(name)
    port_note = (f"default http://localhost:{port}" if port
                 else "see deploy/docker-compose.yml")
    header = TS_HEADER.format(title=model.spec["info"]["title"], name=name)
    models_block = render_ts_models(model)

    used_names: dict[str, int] = {}
    methods: list[str] = []
    for path in sorted(model.spec["paths"]):
        for method in HTTP_METHODS:
            op = model.spec["paths"][path].get(method)
            if not op:
                continue
            methods.append(build_ts_method(model, path, method, op, used_names))

    method_text = "\n\n".join(methods)
    cls = cls_name(name)
    class_text = TS_CLASS_TEMPLATE.format(
        cls=cls, title=model.spec["info"]["title"],
        port_note=port_note, methods=method_text)
    aliases = [a for n, a in sorted(model.aliases.items())
               if re.search(rf"\b{a}\b", f"{models_block}\n{method_text}")]
    parts = [header]
    if models_block:
        parts.append(models_block + "\n\n")
    # The generated methods reference the handwritten transport type. The
    # .js extension is required under NodeNext module resolution.
    parts.append('import { HarnessHttp } from "./runtime.js";\n\n')
    parts.append(class_text.rstrip("\n") + "\n")
    # Public surface of this module: the client class plus every schema alias
    # actually referenced (the TS analogue of the Python module's __all__).
    parts.append("\n/* Module surface (mirrors __all__ in clients/python):\n")
    parts.append(f" * export class {cls}")
    for a in aliases:
        parts.append(f"\n * export interface/type {a}")
    parts.append("\n */\n")
    return "".join(parts)


def generate_ts_services_module(names: list[str]) -> str:
    services_lines = "\n".join(f'  "{n}",' for n in names)
    port_map = "\n".join(
        f'  "{n}": {DEFAULT_PORTS[n]},' for n in names if n in DEFAULT_PORTS)
    return TS_SERVICES_TEMPLATE.format(services_lines=services_lines,
                                       port_map=port_map)


def main() -> int:
    ap = argparse.ArgumentParser(
        description=(__doc__ or "Generate SDK clients from recorded specs.").splitlines()[0])
    ap.add_argument("--target", choices=("python", "ts"), default="python",
                    help="emit the Python SDK (default) or the TypeScript SDK")
    args = ap.parse_args()

    spec_files = sorted(SPECS_DIR.glob("*.openapi.json"))
    if not spec_files:
        raise SystemExit("no specs found — run scripts/sdk-gen/fetch_specs.py first")
    if args.target == "ts":
        return _main_ts(spec_files)
    SDK_DIR.mkdir(parents=True, exist_ok=True)
    names: list[str] = []
    for spec_file in spec_files:
        name = spec_file.name.removesuffix(".openapi.json")
        model = SpecModel(name, json.loads(spec_file.read_text()))
        module_code = generate_service_module(name, model)
        compile(module_code, str(spec_file), "exec")  # fail loudly before writing
        out = SDK_DIR / f"{name}.py"
        out.write_text(module_code)
        n_ops = sum(len([m for m in ops if m in HTTP_METHODS])
                    for ops in model.spec["paths"].values())
        print(f"{name:13} -> clients/python/harness_sdk/{out.name} ({n_ops} operations)")
        names.append(name)
    services_code = generate_services_module(names)
    compile(services_code, "services.py", "exec")
    (SDK_DIR / "services.py").write_text(services_code)
    print(f"{'services':13} -> clients/python/harness_sdk/services.py")
    return 0


def _main_ts(spec_files: list[Path]) -> int:
    """Emit clients/ts/src/<service>.ts + services.ts from the same specs."""
    TS_DIR.mkdir(parents=True, exist_ok=True)
    names: list[str] = []
    for spec_file in spec_files:
        name = spec_file.name.removesuffix(".openapi.json")
        model = SpecModel(name, json.loads(spec_file.read_text()))
        code = generate_ts_service_module(name, model)
        out = TS_DIR / f"{name}.ts"
        out.write_text(code)
        n_ops = sum(len([m for m in ops if m in HTTP_METHODS])
                    for ops in model.spec["paths"].values())
        print(f"{name:13} -> clients/ts/src/{out.name} ({n_ops} operations)")
        names.append(name)
    (TS_DIR / "services.ts").write_text(generate_ts_services_module(names))
    print(f"{'services':13} -> clients/ts/src/services.ts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
