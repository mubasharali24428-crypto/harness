#!/usr/bin/env python3
"""Generate clients/python/harness_sdk/<service>.py from the recorded specs.

Reads scripts/sdk-gen/specs/*.openapi.json (refresh with fetch_specs.py) and
emits one Python module per backend section plus services.py. Request/response
shapes become ``typing.TypedDict`` classes (documentation-grade: wire keys are
the spec's camelCase names; runtime code passes plain dicts). The handwritten
runtime (runtime.py, ws.py, errors.py, client.py) is NEVER touched — rerun
freely after API changes:

    python scripts/sdk-gen/fetch_specs.py && python scripts/sdk-gen/generate.py

Standard library only. Idempotent: same specs -> byte-identical modules.
"""

from __future__ import annotations

import json
import keyword
import re
from pathlib import Path
from typing import Any

SDK_DIR = Path(__file__).resolve().parents[2] / "clients" / "python" / "harness_sdk"
SPECS_DIR = Path(__file__).resolve().parent / "specs"

HTTP_METHODS = ("get", "post", "put", "delete", "patch")

DEFAULT_PORTS = {"identity": 8001, "github": 8002, "router": 8003,
                 "orchestrator": 8004, "sandbox": 8005, "meeting": 8006,
                 "review": 8008}

CLASS_NAMES = {"identity": "IdentityClient", "github": "GithubClient",
               "router": "RouterClient", "orchestrator": "OrchestratorClient",
               "sandbox": "SandboxClient", "meeting": "MeetingClient",
               "review": "ReviewClient"}

HEADER = (
    '''"""{title} section client — GENERATED by scripts/sdk-gen/generate.py.

Source of truth: scripts/sdk-gen/specs/{name}.openapi.json
(recorded from the section's /openapi.json). Do not edit by hand — regenerate:

    python scripts/sdk-gen/fetch_specs.py && python scripts/sdk-gen/generate.py

Every method returns the decoded JSON body and raises
:class:`harness_sdk.errors.ApiError` on any non-2xx (the frozen error envelope
is parsed into ``ApiError.code``). Auth, retries with backoff, and error
parsing live in :mod:`harness_sdk.runtime`.
"""

from __future__ import annotations

import typing

from .runtime import HarnessHTTP
'''
)

CLASS_HEADER = (
    "\n\nclass {cls}:\n"
    '    """Client for the {title} service ({port_note})."""\n'
    "\n"
    "    def __init__(self, http: HarnessHTTP, base_url: str | None = None) -> None:\n"
    "        self._http = http\n"
    "        #: Service base URL; resolved by harness_sdk.client at construction.\n"
    '        self.base_url = (base_url or "").rstrip("/")\n'
)


def cls_name(service: str) -> str:
    return CLASS_NAMES[service]


def snake_case(name: str) -> str:
    """operationId/path fragment -> pythonic snake_case."""
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    s = re.sub(r"[-.\s]+", "_", s)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    out = re.sub(r"[^A-Za-z0-9_]", "", s)
    out = re.sub(r"_+", "_", out).strip("_").lower()
    if not out:
        out = "call"
    if keyword.iskeyword(out) or keyword.issoftkeyword(out):
        out += "_"
    return out


def alias_for(schema_name: str, taken: set[str]) -> str:
    """Schema title -> unique importable alias."""
    base = re.sub(r"[^A-Za-z0-9_]", "", schema_name)
    if not base or base[0].isdigit():
        base = f"Schema{base}"
    alias = base
    n = 2
    while alias in taken or keyword.iskeyword(alias):
        alias = f"{base}_{n}"
        n += 1
    taken.add(alias)
    return alias


def attr_key(prop_name: str, taken: set[str]) -> str:
    """Wire key -> safe TypedDict attribute name (mangles collisions only)."""
    if prop_name.isidentifier() and not keyword.iskeyword(prop_name):
        return prop_name
    base = re.sub(r"\W", "_", prop_name) or "field"
    if base[0].isdigit():
        base = f"f_{base}"
    if keyword.iskeyword(base):
        base += "_"
    candidate, i = base, 2
    while candidate in taken:
        candidate = f"{base}_{i}"
        i += 1
    taken.add(candidate)
    return candidate


class SpecModel:
    """One OpenAPI spec with schema-alias bookkeeping."""

    def __init__(self, name: str, spec: dict[str, Any]) -> None:
        self.name = name
        self.spec = spec
        self.schemas: dict[str, dict[str, Any]] = (
            spec.get("components", {}).get("schemas", {}) or {}
        )
        taken: set[str] = {"HarnessHTTP", "typing"}
        self.aliases: dict[str, str] = {}
        for schema_name in sorted(self.schemas):
            self.aliases[schema_name] = alias_for(schema_name, taken)

    def resolve(self, schema: dict[str, Any] | None) -> str:
        """JSON-schema fragment -> Python type expression."""
        if not isinstance(schema, dict) or not schema:
            return "typing.Any"
        if "$ref" in schema:
            target = schema["$ref"].rsplit("/", 1)[-1]
            return self.aliases.get(target, "typing.Any")
        if "anyOf" in schema:
            branches = [self.resolve(b) for b in schema["anyOf"]]
            non_null = [b for i, b in enumerate(branches)
                        if schema["anyOf"][i].get("type") != "null"]
            had_null = len(non_null) != len(branches)
            uniq = list(dict.fromkeys(non_null or branches))
            joined = " | ".join(uniq)
            return f"{joined} | None" if had_null else joined
        if "enum" in schema:
            vals = ", ".join(repr(v) for v in schema["enum"])
            return f"typing.Literal[{vals}]"
        stype = schema.get("type")
        if stype == "string":
            return "str"
        if stype == "integer":
            return "int"
        if stype == "number":
            return "float"
        if stype == "boolean":
            return "bool"
        if stype == "array":
            return f"list[{self.resolve(schema.get('items'))}]"
        if stype == "object":
            return "dict[str, typing.Any]"
        return "typing.Any"

    def response_type(self, op: dict[str, Any]) -> str:
        responses = op.get("responses", {})
        for code in ("200", "201", "default"):
            rsp = responses.get(code)
            if not isinstance(rsp, dict):
                continue
            json_schema = (rsp.get("content", {}).get("application/json", {})
                           or {}).get("schema")
            if json_schema is not None:
                resolved = self.resolve(json_schema)
                if resolved != "typing.Any" and resolved.endswith(" | None"):
                    # anyOf[T, null] success bodies: keep the payload type.
                    return resolved.replace(" | None", "")
                return resolved
            if rsp.get("content", {}).get("text/plain"):
                return "str"
        return "typing.Any"


def render_models(model: SpecModel) -> str:
    """Emit the TypedDict / TypeAlias block for components.schemas."""
    blocks: list[str] = []
    for schema_name in sorted(model.schemas):
        alias = model.aliases[schema_name]
        s = model.schemas[schema_name]
        props = s.get("properties")
        txt = json.dumps(s)
        if isinstance(props, dict):
            required = list(s.get("required", []))
            taken: set[str] = set()
            rows: list[tuple[str, str, str]] = []  # (attr, type, wire_comment)
            for pn in props:
                ps = props[pn]
                attr = attr_key(pn, taken)
                note = "" if attr == pn else f"  # wire key: {pn!r}"
                req_note = "  # required" if pn in required else ""
                suffix = note + req_note
                rows.append((attr, model.resolve(ps), suffix))
            if not rows:
                blocks.append(
                    f"class {alias}(typing.TypedDict, total=False):\n"
                    f'    """{schema_name} — empty object."""\n'
                )
                continue
            head = f"class {alias}(typing.TypedDict, total=False):"
            req_doc = f" Required keys: {', '.join(required)}." if required else ""
            blocks.append("\n".join([
                head,
                f'    """{schema_name}.{req_doc}"""',
                *[f"    {a}: {t}{x}" for a, t, x in rows],
            ]))
        elif s.get("type") == "array" and '"$ref"' in txt:
            blocks.append(f"{alias}: typing.TypeAlias = "
                          f"{model.resolve(s)}  # {schema_name}")
        elif "enum" in s:
            blocks.append(f"{alias}: typing.TypeAlias = "
                          f"{model.resolve(s)}  # {schema_name}")
        else:
            # Primitive / misc schemas referenced by name somewhere.
            blocks.append(f"{alias}: typing.TypeAlias = "
                          f"{model.resolve(s)}  # {schema_name}")
    return "\n\n".join(blocks)


def build_method(model: SpecModel, path: str, method: str, op: dict[str, Any],
                 used_names: dict[str, int]) -> str:
    """Emit one client method."""
    summary = (op.get("summary") or op.get("operationId") or "").strip()
    raw_parts = re.findall(r"\{([^}]+)\}", path)

    path_param_map: dict[str, str] = {}
    query_items: list[tuple[str, str]] = []
    for p in op.get("parameters", []):
        pname_raw = p.get("name", "")
        pname = snake_case(pname_raw)
        if p.get("in") == "path":
            path_param_map[pname_raw] = pname
        elif p.get("in") == "query":
            query_items.append((pname_raw, pname))

    body_schema = ((op.get("requestBody", {}) or {}).get("content", {})
                   or {}).get("application/json", {}).get("schema")
    body_optional = False
    body_type: str | None = None
    if body_schema is not None:
        body_type = model.resolve(body_schema)
        if body_type.endswith(" | None") or body_type == "None":
            body_optional = True
            body_type = body_type.replace(" | None", "") or "typing.Any"
        elif body_schema.get("type") == "object" and "$ref" not in body_schema \
                and "anyOf" not in body_schema:
            body_optional = True  # free-form object bodies may be omitted
    has_body = body_type is not None

    # -- signature -----------------------------------------------------------
    parts: list[str] = []
    seen: set[str] = set()

    def add_param(name: str, ptype: str, required: bool,
                  default_expr: str | None) -> None:
        nm, i = name, 2
        while nm in seen:
            nm = f"{name}{i}"
            i += 1
        seen.add(nm)
        if required:
            parts.append(f"{nm}: {ptype}")
        else:
            opt_type = ptype if ptype.endswith("| None") else f"{ptype} | None"
            parts.append(f"{nm}: {opt_type} = {default_expr or 'None'}")

    for pname_raw in raw_parts:
        pname = path_param_map.get(pname_raw, snake_case(pname_raw))
        add_param(pname, "str", True, None)
    if has_body:
        add_param("body", body_type, not body_optional, "None")
    param_schemas = {p.get("name"): (p.get("schema") or {})
                     for p in op.get("parameters", [])}
    for qraw, qlocal in query_items:
        add_param(qlocal, model.resolve(param_schemas.get(qraw)), False, "None")

    ret = model.response_type(op)

    # -- method name ----------------------------------------------------------
    op_id = op.get("operationId") or ""
    candidate = snake_case(op_id.split("_api_v1_")[0]) if op_id else ""
    if not candidate or len(candidate) > 60:
        frag = "".join(w.title() for w in re.findall(r"[A-Za-z0-9]+", path))
        candidate = snake_case(f"{method}_{frag}")
    if path == "/health":
        candidate = "health"  # FastAPI opIds here are noisy (health_health_get)
    count = used_names.get(candidate, 0)
    used_names[candidate] = count + 1
    mname = candidate if count == 0 else f"{candidate}_{count + 1}"

    # -- body -----------------------------------------------------------------
    fmt_path = path
    for pname_raw in raw_parts:
        fmt_path = fmt_path.replace(
            "{" + pname_raw + "}",
            "{" + path_param_map.get(pname_raw, snake_case(pname_raw)) + "}",
        )

    lines: list[str] = []
    args_sig = ", ".join(["self", *parts])
    lines.append(f"    def {mname}({args_sig}) -> {ret}:")
    lines.append(f'        """{summary}')
    lines.append("")
    lines.append(f"        {method.upper()} {path}")
    lines.append('        """')
    if fmt_path:
        path_stmt = (f'_path = f"{fmt_path}"' if raw_parts
                     else f'_path = "{fmt_path}"')
    else:
        path_stmt = '_path = "/"'
    lines.append(f"        {path_stmt}")
    call_args = ["self.base_url", f'"{method.upper()}"', "_path"]
    if has_body:
        call_args.append("json_body=body")
    if query_items:
        qpairs = ", ".join(f'"{qraw}": {qlocal}' for qraw, qlocal in query_items)
        lines.append(f"        _params: dict[str, typing.Any] = {{{qpairs}}}")
        call_args.append("params=_params")
    lines.append(f"        return self._http.request({', '.join(call_args)})")
    return "\n".join(lines)


def generate_service_module(name: str, model: SpecModel) -> str:
    port = DEFAULT_PORTS.get(name)
    port_note = (f"default http://localhost:{port}" if port
                 else "see deploy/docker-compose.yml")
    header = HEADER.format(title=model.spec["info"]["title"], name=name)
    models_block = render_models(model)
    class_head = CLASS_HEADER.format(cls=cls_name(name),
                                     title=model.spec["info"]["title"],
                                     port_note=port_note)

    used_names: dict[str, int] = {}
    methods: list[str] = []
    for path in sorted(model.spec["paths"]):
        for method in HTTP_METHODS:
            op = model.spec["paths"][path].get(method)
            if not op:
                continue
            methods.append(build_method(model, path, method, op, used_names))
            methods.append("")

    method_text = "\n".join(methods).rstrip("\n")
    aliases = [a for n, a in sorted(model.aliases.items())
               if re.search(rf"\b{a}\b", f"{models_block}\n{method_text}")]
    exports = ", ".join([f'"{cls_name(name)}"'] + [f'"{a}"' for a in aliases])
    parts = [header]
    if models_block:
        parts.append("\n\n" + models_block)
    parts.append(class_head)
    if method_text:
        parts.append("\n\n" + method_text)
    parts.append(f"\n\n\n__all__ = [{exports}]\n")
    return "".join(parts)


SERVICES_TEMPLATE = (
    "# Generated by scripts/sdk-gen/generate.py — do not edit by hand.\n"
    '"""Service-name registry for the generated section clients."""\n'
    "\n"
    "from __future__ import annotations\n"
    "\n"
    "#: Service keys, matching scripts/sdk-gen/specs/*.openapi.json.\n"
    "SERVICES: tuple[str, ...] = ({services_tuple})\n"
    "\n"
    "#: Generated client class for each service key.\n"
    "CLIENT_CLASSES: dict[str, str] = {{\n"
    "{class_map}\n"
    "}}\n"
)


def generate_services_module(names: list[str]) -> str:
    class_map = ",\n".join(f'    "{n}": "{cls_name(n)}"' for n in names)
    tup = (", ".join(f'"{n}"' for n in names) + ",") if names else ""
    return SERVICES_TEMPLATE.format(services_tuple=tup, class_map=class_map)


def main() -> int:
    spec_files = sorted(SPECS_DIR.glob("*.openapi.json"))
    if not spec_files:
        raise SystemExit("no specs found — run scripts/sdk-gen/fetch_specs.py first")
    SDK_DIR.mkdir(parents=True, exist_ok=True)
    names: list[str] = []
    for spec_file in spec_files:
        name = spec_file.name.removesuffix(".openapi.json")
        model = SpecModel(name, json.loads(spec_file.read_text()))
        module_code = generate_service_module(name, model)
        compile(module_code, str(spec_file), "exec")  # fail loudly before writing
        out = SDK_DIR / f"{name}.py"
        out.write_text(module_code)
        n_ops = sum(len([m for m in ops if m in HTTP_METHODS])
                    for ops in model.spec["paths"].values())
        print(f"{name:13} -> clients/python/harness_sdk/{out.name} ({n_ops} operations)")
        names.append(name)
    services_code = generate_services_module(names)
    compile(services_code, "services.py", "exec")
    (SDK_DIR / "services.py").write_text(services_code)
    print(f"{'services':13} -> clients/python/harness_sdk/services.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
